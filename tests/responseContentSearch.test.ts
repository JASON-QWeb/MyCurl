// @vitest-environment jsdom
import { act } from 'react';
import { expect, it, vi } from 'vitest';
import { useAppStore } from '../src/store/useAppStore';
import * as util from '../src/lib/util';
import { button, click, typeInput } from './renderComponent';
import { showResponses } from './renderResponsePane';

const records = [{ body: '[{"name":"Janis","notes":"Janis again"},{"name":"FYY"}]' }];
function press(el: Element, key: string, options?: KeyboardEventInit) {
  const event = new KeyboardEvent('keydown', { key, bubbles: true, cancelable: true, ...options });
  act(() => { el.dispatchEvent(event); });
  return event.defaultPrevented;
}
it('locates, navigates, filters, copies and downloads the visible JSON', async () => {
  const { container, req } = showResponses({ records });
  const save = vi.fn().mockResolvedValue({ filename: 'test.json' });
  act(() => useAppStore.setState({ saveAndRecordDownload: save }));
  await click(button(container, 'Find / Filter'));
  const input = container.querySelector<HTMLInputElement>('.resp-search-bar input')!;
  typeInput(input, 'Janis');
  const editor = container.querySelector('.cm-editor');
  expect(editor?.textContent).toContain('FYY');
  expect(editor?.querySelectorAll('.cm-resp-match')).toHaveLength(2);
  expect(editor?.querySelectorAll('.cm-resp-match')[0].classList.contains('cm-resp-match-active')).toBe(true);
  press(input, 'Enter');
  expect(editor?.querySelectorAll('.cm-resp-match')[1].classList.contains('cm-resp-match-active')).toBe(true);
  press(input, 'Enter', { shiftKey: true });
  expect(container.querySelector('[role=status]')?.textContent).toBe('1 / 2');
  await click(button(container, 'Filter'));
  expect(container.querySelector('.cm-editor')).toBe(editor);
  expect(editor?.textContent).not.toContain('FYY');
  expect(editor?.querySelectorAll('.cm-resp-match')).toHaveLength(2);
  const copy = vi.spyOn(util, 'copyText').mockResolvedValue();
  await click(button(container, 'Copy response'));
  await click(button(container, 'Download response'));
  expect(JSON.parse(copy.mock.lastCall![0])).toEqual([JSON.parse(records[0].body)[0]]);
  expect(save).toHaveBeenCalledWith(expect.objectContaining({ text: copy.mock.lastCall![0], filename: expect.stringMatching(/-filtered\.json$/) }));
  expect(container.querySelector('.download-saved')).toBeTruthy();
  expect(useAppStore.getState().data.requests.find(r => r.id === req.id)?.responseFilter).toBe(req.responseFilter);
  typeInput(input, 'absent');
  expect(container.querySelector('.empty-state')?.textContent).toContain('No matches for "absent"');
  await click(button(container, 'Clear filter'));
  expect(editor === container.querySelector('.cm-editor')).toBe(false);
  expect(container.querySelector('.cm-editor')?.textContent).toContain('FYY');
});
it('recovers a literal jq error and supports invalid regex, Escape and focus scope', async () => {
  const { container, req } = showResponses({ records });
  const outside = document.body.appendChild(document.createElement('input'));
  outside.focus();
  expect(press(outside, 'f', { ctrlKey: true })).toBe(false);
  outside.blur();
  const modal = document.body.appendChild(document.createElement('div'));
  modal.setAttribute('role', 'dialog');
  expect(press(document.body, 'f', { ctrlKey: true })).toBe(false);
  modal.remove();
  expect(press(document.body, 'f', { metaKey: true })).toBe(true);
  expect(document.activeElement).toBe(container.querySelector('.resp-search-bar input'));
  act(() => useAppStore.getState().updateRequest(req.id, { responseFilter: 'Janis' }));
  await click(button(container, 'Filter body for "Janis"'));
  expect(container.querySelector('.jq-error')).toBeNull();
  expect(useAppStore.getState().data.requests.find(r => r.id === req.id)?.responseFilter).toBe('');
  expect(container.querySelector('.cm-editor')?.textContent).not.toContain('FYY');
  const input = container.querySelector<HTMLInputElement>('.resp-search-bar input')!;
  expect(input.value).toBe('Janis');
  await click(button(container, 'Regular expression'));
  typeInput(input, '[');
  expect(container.querySelector('[role=status]')?.textContent).toContain('Invalid regex');
  press(input, 'Escape');
  expect(input.value).toBe('');
  press(input, 'Escape');
  expect(container.querySelector('.resp-search-bar')).toBeNull();
});
it('searches stream events by name and data and keeps original numbers', async () => {
  const body = 'event: first\ndata: skip\n\nevent: delta\ndata: yes\n\nevent: last\ndata: delta\n\n';
  const { container } = showResponses({ records: [{ body, contentType: 'text/event-stream' }] });
  await click(button(container, 'Find / Filter'));
  const input = container.querySelector<HTMLInputElement>('.resp-search-bar input')!;
  typeInput(input, 'delta');
  await click(button(container, 'Filter'));
  const rows = container.querySelectorAll('.sse-event-row');
  expect([...rows].map(row => row.firstElementChild?.textContent)).toEqual(['#2', '#3']);
  expect(rows[0].querySelector('.cm-resp-match-active')).toBeTruthy();
  press(input, 'Enter');
  expect(rows[1].querySelector('.cm-resp-match-active')).toBeTruthy();
  const copy = vi.spyOn(util, 'copyText').mockResolvedValue();
  await click(button(container, 'Copy response'));
  expect(copy.mock.lastCall![0]).toBe('event: delta\ndata: yes\n\nevent: last\ndata: delta');
  await click(button(container, 'Chat'));
  expect(container.querySelector('.resp-search-bar')).toBeNull();
});

it.each(['metaKey', 'ctrlKey'] as const)('handles %s+F inside CodeMirror, selects the query on repeat and respects the headers tab', async mod => {
  const { container } = showResponses({ records });
  const content = container.querySelector<HTMLElement>('.cm-content')!;
  content.tabIndex = 0;
  content.focus();
  const string = [...content.querySelectorAll('span')].find(s => s.firstChild?.nodeValue?.includes('Janis'))!.firstChild!;
  const start = string.nodeValue!.indexOf('Janis');
  const range = document.createRange();
  range.setStart(string, start);
  range.setEnd(string, start + 5);
  window.getSelection()!.removeAllRanges();
  window.getSelection()!.addRange(range);
  expect(press(content, 'f', { [mod]: true })).toBe(true);
  const input = container.querySelector<HTMLInputElement>('.resp-search-bar input')!;
  expect(document.activeElement).toBe(input);
  expect(input.value).toBe('Janis');
  expect([input.selectionStart, input.selectionEnd]).toEqual([0, 5]);
  window.getSelection()!.removeAllRanges();
  typeInput(input, 'changed');
  input.setSelectionRange(4, 4);
  expect(press(input, 'f', { [mod]: true })).toBe(true);
  expect([input.selectionStart, input.selectionEnd]).toEqual([0, 7]);
  expect(container.querySelector('.cm-search')).toBeNull();
  const headers = button(container, 'Headers0');
  await click(headers);
  headers.focus();
  expect(press(headers, 'f', { [mod]: true })).toBe(true);
  expect(document.activeElement).toBe(container.querySelector('[data-response-header-filter]'));
  (document.activeElement as HTMLElement).blur();
  expect(press(document.body, 'f', { [mod]: true })).toBe(true);
  expect(document.activeElement).toBe(container.querySelector('.resp-search-bar input'));
});

it('downloads binary image bytes and preserves the MIME type', async () => {
  const { container } = showResponses({ records: [{ body: '', bodyBase64: 'AAE=', contentType: 'image/png' }] });
  const save = vi.fn().mockResolvedValue({});
  act(() => useAppStore.setState({ saveAndRecordDownload: save }));
  await click(button(container, 'Download response'));
  expect(save).toHaveBeenCalledWith(expect.objectContaining({ base64: 'AAE=', mimeType: 'image/png', filename: expect.stringMatching(/\.png$/) }));
  expect(save.mock.calls[0][0].text).toBeUndefined();
});
it('exports matching raw NDJSON lines without reformatting individual objects', async () => {
  const body = '{"model":"m","done":false,"response":"first"}\n{"model":"m","done":true,"response":"second"}';
  const { container } = showResponses({ records: [{ body, contentType: 'application/x-ndjson' }] });
  await click(button(container, 'Raw'));
  await click(button(container, 'Find / Filter'));
  typeInput(container.querySelector('.resp-search-bar input')!, 'second');
  await click(button(container, 'Filter'));
  const save = vi.fn().mockResolvedValue({});
  act(() => useAppStore.setState({ saveAndRecordDownload: save }));
  await click(button(container, 'Download response'));
  expect(save).toHaveBeenCalledWith(expect.objectContaining({ text: body.split('\n')[1], filename: expect.stringMatching(/-filtered\.ndjson$/) }));
});
